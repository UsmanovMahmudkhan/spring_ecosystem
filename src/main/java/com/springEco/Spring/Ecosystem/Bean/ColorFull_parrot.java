package com.springEco.Spring.Ecosystem.Bean;

public class ColorFull_parrot {
    String name;
    String color;

    public ColorFull_parrot(String name, String color) {
        this.name = name;
        this.color = color;
    }

    public String getColor() {
        return color;
    }

    public void setColor(String color) {
        this.color = color;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
